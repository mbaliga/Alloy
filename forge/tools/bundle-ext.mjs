// Builds a package's main.js from the shared voxel core and the package's own source, because a package Worker loads ONE file:
//   node tools/bundle-ext.mjs            writes examples/ext/{thermal-3d,structural,airflow,runner}/main.js   (npm run build:ext)
//   node tools/bundle-ext.mjs --check    exits 1 if a committed main.js is stale (run by test_thermal3d.mjs and test_structural.mjs)
// The core files have no imports between them; `export ` is stripped so everything lands in the package function's scope.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CORE = ['correlations.js', 'grid.js', 'cg.js', 'gpu.js'];
const CORE_STRUCTURAL = ['grid.js', 'cg.js', 'elastic.js', 'gpu-elastic.js'];
const CORE_AIRFLOW = ['grid.js', 'lbm.js', 'gpu-lbm.js'];
const strip = (s) => s.replace(/^export (async function|function\*|function|const|let|class)/gm, '$1');

// Files outside voxel-core that a package bundles: shared by the Runner server and the Forge client (one parser for both sides).
const RUNNER_SHARED = ['../runner/src/lib/stl.js', '../runner/src/lib/vtu.js'];

export const TARGETS = {
  'thermal-3d': { src: 'analysis/thermal-3d/package-main.js', out: 'examples/ext/thermal-3d/main.js', core: CORE },
  'structural': { src: 'analysis/structural/package-main.js', out: 'examples/ext/structural/main.js', core: CORE_STRUCTURAL },
  'airflow': { src: 'analysis/airflow/package-main.js', out: 'examples/ext/airflow/main.js', core: CORE_AIRFLOW },
  'runner': { src: 'analysis/runner/package-main.js', out: 'examples/ext/runner/main.js', core: [], extra: RUNNER_SHARED },
};

export function bundle(name) {
  const t = TARGETS[name], parts = [`// GENERATED by tools/bundle-ext.mjs from ${t.core.length ? 'analysis/voxel-core/*.js' : (t.extra || []).map((f) => f.replace('../', '')).join(', ')} and ${t.src}. Do not edit: edit those and run npm run build:ext.`];
  for (const f of t.core) parts.push(`// ───────── voxel core: ${f} ─────────\n` + strip(fs.readFileSync(path.join(ROOT, 'analysis/voxel-core', f), 'utf8')));
  for (const f of t.extra || []) parts.push(`// ───────── shared with the runner: ${path.basename(f)} ─────────\n` + strip(fs.readFileSync(path.join(ROOT, f), 'utf8')));
  parts.push(`// ───────── package: ${path.basename(t.src)} ─────────\n` + strip(fs.readFileSync(path.join(ROOT, t.src), 'utf8')));
  return parts.join('\n');
}

/** The core as one script that evaluates to an object of its exports (for browser tests and Workers). */
export function coreScript(name = 'thermal-3d') {
  const src = TARGETS[name].core.map((f) => fs.readFileSync(path.join(ROOT, 'analysis/voxel-core', f), 'utf8'));
  const names = [...src.join('\n').matchAll(/^export (?:async function\*?|function\*?|const|let|class) ([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
  return `(function(){${src.map(strip).join('\n')}\nreturn {${names.join(',')}};})()`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check'); let stale = false;
  for (const name of Object.keys(TARGETS)) {
    const out = path.join(ROOT, TARGETS[name].out), text = bundle(name);
    if (check) { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) { console.error(`${TARGETS[name].out} is stale: run npm run build:ext`); stale = true; } }
    else { fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, text); console.log('wrote', TARGETS[name].out); }
  }
  process.exit(stale ? 1 : 0);
}
