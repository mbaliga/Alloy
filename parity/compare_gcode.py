#!/usr/bin/env python3
"""Compare desktop and Android slicer G-code semantically for Alloy G3.

Inputs may be plain .gcode or Bambu/Orca .gcode.3mf archives. For archives the
first Metadata/plate_*.gcode member is used unless --plate-member is supplied.

The comparator intentionally ignores volatile metadata and does not require
byte-for-byte output. It compares:
- ordered feature-type transitions;
- layer count / Z progression;
- extrusion and travel move counts;
- approximate positive extrusion distance;
- reported print time and filament usage when both sides expose them.

G3 requires reported print time and filament use within 2% when available, and
no missing major toolpath feature classes. The report records unavailable
metrics rather than inventing them.
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import asdict, dataclass, field
import json
import math
from pathlib import Path
import re
from typing import Iterable
from zipfile import ZipFile

FLOAT = r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?"
TOKEN_RE = re.compile(r"([A-Za-z])(" + FLOAT + r")")
M204_RE = re.compile(r"^M204(?:\s+(.+?))?(?:\s*;.*)?$", re.I)

# Common Orca/Bambu/Prusa feature annotations. Keep this conservative: unknown
# comments are ignored instead of guessed into a feature class.
FEATURE_PATTERNS = [
    re.compile(r"^;\s*TYPE\s*:\s*(.+?)\s*$", re.I),
    re.compile(r"^;\s*FEATURE\s*:\s*(.+?)\s*$", re.I),
    re.compile(r"^;\s*LINE_TYPE\s*:\s*(.+?)\s*$", re.I),
]

MODEL_TIME_PATTERNS = [
    re.compile(r"model printing time.*?(?:=|:)\s*([^;]+)", re.I),
]
TOTAL_TIME_PATTERNS = [
    re.compile(r"total estimated time.*?(?:=|:)\s*([^;]+)", re.I),
]
TIME_PATTERNS = [
    re.compile(r"estimated printing time.*?(?:=|:)\s*([^;]+)", re.I),
]
FILAMENT_MM_PATTERNS = [
    re.compile(r"filament used(?!\s+for wipe tower) \[mm\].*?(?:=|:)\s*(.+)", re.I),
    re.compile(r"total filament used(?!\s+for wipe tower).*?\[mm\].*?(?:=|:)\s*(.+)", re.I),
    re.compile(r"total filament length \[mm\].*?(?:=|:)\s*(.+)", re.I),
]
FILAMENT_G_PATTERNS = [
    re.compile(r"filament used(?!\s+for wipe tower) \[g\].*?(?:=|:)\s*(.+)", re.I),
    re.compile(r"total filament used(?!\s+for wipe tower).*?\[g\].*?(?:=|:)\s*(.+)", re.I),
    re.compile(r"total filament weight \[g\].*?(?:=|:)\s*(.+)", re.I),
]

DECLARED_LAYER_RE = re.compile(r"total layer number\s*:\s*(\d+)", re.I)
LAYER_MARKER_RE = re.compile(r"^;\s*LAYER\s*:\s*(-?\d+)\s*$", re.I)
CHANGE_LAYER_RE = re.compile(r"^;\s*CHANGE_LAYER\b", re.I)
MODEL_LAYER_START_RE = re.compile(r"^;\s*LAYER_CHANGE\s*$", re.I)

VOLATILE_PREFIXES = (
    "; generated by ",
    "; generated at ",
    "; creation_date",
    "; timestamp",
)


@dataclass
class Metrics:
    source: str
    archive_member: str | None
    line_count: int
    layer_count: int
    z_levels: list[float]
    extrusion_moves: int
    travel_moves: int
    positive_e_mm: float
    linear_xyz_path_mm: float
    arc_path_mm: float
    nominal_linear_extrusion_seconds: float
    nominal_linear_travel_seconds: float
    nominal_arc_extrusion_seconds: float
    nominal_arc_travel_seconds: float
    unsupported_arc_moves: int
    feature_transitions: list[str]
    feature_counts: dict[str, int]
    feature_extrusion_path_mm: dict[str, float]
    feature_positive_e_mm: dict[str, float]
    extrusion_accounting: dict[str, dict[str, float]]
    # Diagnostic inputs only. The ordered segment stream is omitted from the
    # JSON report; compare() reduces it to a bounded first-difference sample.
    travel_by_layer_feedrate: dict[str, dict[str, float]]
    travel_segments: list[tuple]
    print_time_seconds: float | None
    filament_mm: float | None
    filament_g: float | None


def read_gcode(path: Path, plate_member: str | None) -> tuple[str, str | None]:
    lower = path.name.lower()
    if lower.endswith(".3mf") or lower.endswith(".zip"):
        with ZipFile(path) as zf:
            names = zf.namelist()
            if plate_member:
                if plate_member not in names:
                    raise SystemExit(f"Archive member not found: {plate_member}")
                member = plate_member
            else:
                candidates = sorted(
                    n for n in names
                    if re.fullmatch(r"Metadata/plate_\d+\.gcode", n, re.I)
                )
                if not candidates:
                    candidates = sorted(n for n in names if n.lower().endswith(".gcode"))
                if not candidates:
                    raise SystemExit(f"No .gcode member found in {path}")
                member = candidates[0]
            return zf.read(member).decode("utf-8", errors="replace"), member
    return path.read_text(errors="replace"), None


def parse_duration(value: str) -> float | None:
    s = value.strip().lower()
    # Orca/Prusa comments commonly use 1d 2h 3m 4s. Also accept HH:MM:SS.
    if re.fullmatch(r"\d+(?::\d+){1,2}", s):
        parts = [int(x) for x in s.split(":")]
        if len(parts) == 2:
            return float(parts[0] * 60 + parts[1])
        return float(parts[0] * 3600 + parts[1] * 60 + parts[2])
    total = 0.0
    found = False
    for amount, unit in re.findall(r"(" + FLOAT + r")\s*([dhms])", s):
        found = True
        factor = {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit]
        total += float(amount) * factor
    return total if found else None


def parse_number_list(value: str) -> float | None:
    nums = re.findall(FLOAT, value)
    return sum(float(x) for x in nums) if nums else None


def last_matching(lines: Iterable[str], patterns: list[re.Pattern[str]], parser) -> float | None:
    result = None
    for line in lines:
        for pattern in patterns:
            m = pattern.search(line)
            if m:
                parsed = parser(m.group(1))
                if parsed is not None:
                    result = parsed
    return result


def canonical_feature(raw: str) -> str:
    value = re.sub(r"\s+", " ", raw.strip()).lower()
    aliases = {
        "outer wall": "outer_wall",
        "external perimeter": "outer_wall",
        "inner wall": "inner_wall",
        "perimeter": "inner_wall",
        "sparse infill": "sparse_infill",
        "internal infill": "sparse_infill",
        "solid infill": "solid_infill",
        "internal solid infill": "solid_infill",
        "top surface": "top_surface",
        "top solid infill": "top_surface",
        "bottom surface": "bottom_surface",
        "support": "support",
        "support material": "support",
        "support interface": "support_interface",
        "support material interface": "support_interface",
        "bridge": "bridge",
        "bridge infill": "bridge",
        "overhang wall": "overhang_wall",
        "overhang perimeter": "overhang_wall",
        "gap infill": "gap_fill",
        "skirt": "skirt",
        "skirt/brim": "skirt",
        "brim": "skirt",
        "prime tower": "prime_tower",
        "wipe tower": "prime_tower",
    }
    return aliases.get(value, value.replace(" ", "_"))


def declared_layer_count(lines: Iterable[str], fallback: int) -> int:
    """Return the slicer's declared layer count when it has one.

    Bambu writes an authoritative ``total layer number`` header. SliceBeam
    writes numbered ``;LAYER:n`` comments starting at one, while the small
    unit fixtures and the fallback emitter use Z moves. This keeps startup
    positioning moves out of the parity metric without pretending that every
    slicer uses the same comment spelling.
    """
    for line in lines:
        match = DECLARED_LAYER_RE.search(line)
        if match:
            return int(match.group(1))

    markers = [int(match.group(1)) for line in lines
               if (match := LAYER_MARKER_RE.match(line.strip()))]
    if markers:
        unique = set(markers)
        # Both zero-based and one-based slicers describe the highest layer
        # number, so the number of layers is still max+1. Do not count a
        # missing/duplicated marker as a new layer.
        if min(unique) >= 0:
            return max(unique) + 1
        return len(unique)

    change_layers = sum(1 for line in lines if CHANGE_LAYER_RE.match(line.strip()))
    return change_layers if change_layers else fallback


def feature_from_comment(line: str) -> str | None:
    for pattern in FEATURE_PATTERNS:
        m = pattern.match(line)
        if m:
            return canonical_feature(m.group(1))
    return None


# Different slicer families use different labels for the same geometric role.
# These are deliberately reported as aliases in the JSON instead of silently
# being folded into canonical_feature(), so a reviewer can see where the
# engines made a semantic rather than textual match.
FEATURE_ROLE_ALIASES = {
    "bottom_surface": ("solid_infill",),
    "floating_vertical_shell": ("outer_wall",),
    "inner_wall": ("gap_fill",),
    # Bambu labels this sparse roof-repair role `Bridge`; the pinned
    # Orca/Prusa writer labels the same deposited path `Internal bridge`.
    # Keep it visible as an alias so the report distinguishes nomenclature
    # from a genuinely missing bridge toolpath.
    "bridge": ("internal_bridge",),
}


def parse_metrics(path: Path, plate_member: str | None) -> Metrics:
    text, member = read_gcode(path, plate_member)
    lines = text.splitlines()
    has_layer_markers = any(
        MODEL_LAYER_START_RE.match(line.strip())
        or CHANGE_LAYER_RE.match(line.strip())
        or LAYER_MARKER_RE.match(line.strip())
        for line in lines
    )
    model_started = not has_layer_markers

    feature_transitions: list[str] = []
    feature_counts: Counter[str] = Counter()
    feature_extrusion_path_mm: Counter[str] = Counter()
    feature_positive_e_mm: Counter[str] = Counter()
    # Emitted-program accounting, not an assertion that firmware executes
    # conditional macros or that every positive E movement deposits plastic.
    # Do not subtract this ledger from the strict header/geometry checks.
    extrusion_accounting: dict[str, Counter[str]] = {}
    active_feature: str | None = None
    z_levels: list[float] = []
    seen_z: set[float] = set()
    extrusion_moves = 0
    travel_moves = 0
    positive_e_mm = 0.0
    linear_xyz_path_mm = 0.0
    arc_path_mm = 0.0
    nominal_linear_extrusion_seconds = 0.0
    nominal_linear_travel_seconds = 0.0
    nominal_arc_extrusion_seconds = 0.0
    nominal_arc_travel_seconds = 0.0
    unsupported_arc_moves = 0
    travel_by_layer_feedrate: dict[str, Counter[str]] = {}
    travel_segments: list[tuple] = []
    active_layer = -1

    xyz = {"X": 0.0, "Y": 0.0, "Z": 0.0}
    e_value = 0.0
    feedrate_mm_min = 0.0
    absolute_xyz = True
    absolute_e = True
    absolute_arc_center = False
    active_plane = "G17"

    for raw_line in lines:
        line = raw_line.strip()
        if not line:
            continue
        if (MODEL_LAYER_START_RE.match(line)
                or CHANGE_LAYER_RE.match(line)
                or LAYER_MARKER_RE.match(line)):
            model_started = True
            active_layer += 1
            continue
        lower = line.lower()
        if lower.startswith(VOLATILE_PREFIXES):
            continue

        feature = feature_from_comment(line)
        if feature is not None:
            active_feature = feature
            if model_started:
                feature_counts[feature] += 1
                if not feature_transitions or feature_transitions[-1] != feature:
                    feature_transitions.append(feature)
            continue

        code = line.split(";", 1)[0].strip()
        if not code:
            continue
        command = code.split(maxsplit=1)[0].upper()
        if command in {"G17", "G18", "G19"}:
            active_plane = command
            continue
        if command == "G90":
            absolute_xyz = True
            continue
        if command == "G91":
            absolute_xyz = False
            continue
        if command == "G90.1":
            absolute_arc_center = True
            continue
        if command == "G91.1":
            absolute_arc_center = False
            continue
        if command == "M82":
            absolute_e = True
            continue
        if command == "M83":
            absolute_e = False
            continue
        if command == "G92":
            vals = {k.upper(): float(v) for k, v in TOKEN_RE.findall(code)}
            if "E" in vals:
                e_value = vals["E"]
            for axis in "XYZ":
                if axis in vals:
                    xyz[axis] = vals[axis]
            continue
        if command not in {"G0", "G1", "G2", "G3"}:
            continue

        vals = {k.upper(): float(v) for k, v in TOKEN_RE.findall(code)}
        moved_xyz = any(k in vals for k in "XYZ")
        if "F" in vals:
            feedrate_mm_min = vals["F"]

        previous_xyz = xyz.copy()

        if "Z" in vals:
            new_z = vals["Z"] if absolute_xyz else xyz["Z"] + vals["Z"]
            if model_started:
                rounded = round(new_z, 5)
                if rounded not in seen_z:
                    seen_z.add(rounded)
                    z_levels.append(rounded)
            xyz["Z"] = new_z
        for axis in "XY":
            if axis in vals:
                xyz[axis] = vals[axis] if absolute_xyz else xyz[axis] + vals[axis]

        positive_e = 0.0
        if "E" in vals:
            if absolute_e:
                delta = vals["E"] - e_value
                e_value = vals["E"]
            else:
                delta = vals["E"]
                e_value += delta
            scope = ("unscoped" if not has_layer_markers else
                     "after_first_layer" if model_started else "before_first_layer")
            ledger = extrusion_accounting.setdefault(scope, Counter())
            ledger["net_e_mm"] += delta
            if delta > 0:
                # E-only recovery/purge must not be counted as positive E
                # commanded with XYZ. Full-circle arcs may omit endpoint axes.
                key = ("positive_xyz_e_mm" if moved_xyz or command in {"G2", "G3"}
                       else "positive_e_only_mm")
                ledger[key] += delta
            elif delta < 0:
                ledger["retracted_e_mm"] -= delta
            if delta > 0:
                positive_e = delta
                if model_started:
                    positive_e_mm += delta

        if model_started and positive_e > 0:
            extrusion_moves += 1
            if active_feature is not None:
                feature_positive_e_mm[active_feature] += positive_e
        elif model_started and moved_xyz:
            travel_moves += 1

        if model_started and moved_xyz:
            motion_distance = None
            motion_kind = "arc" if command in {"G2", "G3"} else "linear"
            if command in {"G2", "G3"}:
                if active_plane != "G17" or "R" in vals or not {"I", "J"}.issubset(vals):
                    # Only XY-plane center-offset arcs are currently modeled.
                    unsupported_arc_moves += 1
                else:
                    center_x = vals["I"] if absolute_arc_center else previous_xyz["X"] + vals["I"]
                    center_y = vals["J"] if absolute_arc_center else previous_xyz["Y"] + vals["J"]
                    radius_start = math.hypot(previous_xyz["X"] - center_x, previous_xyz["Y"] - center_y)
                    radius_end = math.hypot(xyz["X"] - center_x, xyz["Y"] - center_y)
                    radius = (radius_start + radius_end) / 2.0
                    radii_agree = abs(radius_start - radius_end) <= max(0.05, radius * 0.01)
                    if radius <= 0 or not radii_agree:
                        unsupported_arc_moves += 1
                    else:
                        start_angle = math.atan2(previous_xyz["Y"] - center_y, previous_xyz["X"] - center_x)
                        end_angle = math.atan2(xyz["Y"] - center_y, xyz["X"] - center_x)
                        if command == "G2":
                            sweep = (start_angle - end_angle) % (2.0 * math.pi)
                        else:
                            sweep = (end_angle - start_angle) % (2.0 * math.pi)
                        if math.isclose(sweep, 0.0, abs_tol=1e-9):
                            sweep = 2.0 * math.pi
                        arc_xy = radius * sweep
                        distance = math.hypot(arc_xy, xyz["Z"] - previous_xyz["Z"])
                        motion_distance = distance
                        arc_path_mm += distance
                        if active_feature is not None and positive_e > 0:
                            feature_extrusion_path_mm[active_feature] += distance
                        if feedrate_mm_min > 0:
                            nominal_seconds = distance * 60.0 / feedrate_mm_min
                            if positive_e > 0:
                                nominal_arc_extrusion_seconds += nominal_seconds
                            else:
                                nominal_arc_travel_seconds += nominal_seconds
            elif command in {"G0", "G1"}:
                distance = math.sqrt(sum(
                    (xyz[axis] - previous_xyz[axis]) ** 2 for axis in "XYZ"
                ))
                motion_distance = distance
                linear_xyz_path_mm += distance
                if active_feature is not None and positive_e > 0:
                    feature_extrusion_path_mm[active_feature] += distance
                if feedrate_mm_min > 0:
                    nominal_seconds = distance * 60.0 / feedrate_mm_min
                    if positive_e > 0:
                        nominal_linear_extrusion_seconds += nominal_seconds
                    else:
                        nominal_linear_travel_seconds += nominal_seconds
            # This is a program-level diagnostic, not a firmware travel-time
            # model. Positive-E moves stay classified as extrusion as above.
            if positive_e <= 0 and motion_distance is not None:
                layer = max(active_layer, 0)
                feedrate = round(feedrate_mm_min, 3)
                group_key = f"layer={layer},feedrate_mm_min={feedrate:g}"
                group = travel_by_layer_feedrate.setdefault(
                    group_key, Counter()
                )
                group["moves"] += 1
                group["distance_mm"] += motion_distance
                nominal_seconds = (
                    motion_distance * 60.0 / feedrate if feedrate > 0 else 0.0
                )
                group["nominal_seconds"] += nominal_seconds
                travel_segments.append((
                    layer, command, feedrate,
                    round(previous_xyz["X"], 3), round(previous_xyz["Y"], 3), round(previous_xyz["Z"], 3),
                    round(xyz["X"], 3), round(xyz["Y"], 3), round(xyz["Z"], 3),
                    round(motion_distance, 3), motion_kind,
                ))

    # Bambu's total estimate includes machine warm-up and other orchestration
    # time that the native slicer does not report. Prefer model time when it is
    # available; retain total time as a diagnostic fallback only.
    print_time = last_matching(lines, MODEL_TIME_PATTERNS, parse_duration)
    if print_time is None:
        print_time = last_matching(lines, TIME_PATTERNS, parse_duration)
    if print_time is None:
        print_time = last_matching(lines, TOTAL_TIME_PATTERNS, parse_duration)
    filament_mm = last_matching(lines, FILAMENT_MM_PATTERNS, parse_number_list)
    filament_g = last_matching(lines, FILAMENT_G_PATTERNS, parse_number_list)

    return Metrics(
        source=str(path),
        archive_member=member,
        line_count=len(lines),
        layer_count=declared_layer_count(lines, len(z_levels)),
        z_levels=z_levels,
        extrusion_moves=extrusion_moves,
        travel_moves=travel_moves,
        positive_e_mm=positive_e_mm,
        linear_xyz_path_mm=linear_xyz_path_mm,
        arc_path_mm=arc_path_mm,
        nominal_linear_extrusion_seconds=nominal_linear_extrusion_seconds,
        nominal_linear_travel_seconds=nominal_linear_travel_seconds,
        nominal_arc_extrusion_seconds=nominal_arc_extrusion_seconds,
        nominal_arc_travel_seconds=nominal_arc_travel_seconds,
        unsupported_arc_moves=unsupported_arc_moves,
        feature_transitions=feature_transitions,
        feature_counts=dict(feature_counts),
        feature_extrusion_path_mm=dict(feature_extrusion_path_mm),
        feature_positive_e_mm=dict(feature_positive_e_mm),
        extrusion_accounting={scope: dict(values)
                              for scope, values in extrusion_accounting.items()},
        travel_by_layer_feedrate={scope: dict(values)
                                  for scope, values in travel_by_layer_feedrate.items()},
        travel_segments=travel_segments,
        print_time_seconds=print_time,
        filament_mm=filament_mm,
        filament_g=filament_g,
    )


def acceleration_signature(path: Path, plate_member: str | None) -> list[tuple[str, float]]:
    """Return the ordered acceleration intent emitted by each slicer.

    Orca/Bambu commonly encode the print acceleration with ``M204 S`` while
    SliceBeam uses ``M204 P``. Treat those spellings as the same canonical
    print-acceleration channel, but preserve travel/retract channels so a
    genuinely different motion policy remains visible in the report.
    """
    text, _ = read_gcode(path, plate_member)
    signature: list[tuple[str, float]] = []
    has_layer_markers = any(
        MODEL_LAYER_START_RE.match(line.strip())
        or CHANGE_LAYER_RE.match(line.strip())
        or LAYER_MARKER_RE.match(line.strip())
        for line in text.splitlines()
    )
    model_started = not has_layer_markers
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if (MODEL_LAYER_START_RE.match(line)
                or CHANGE_LAYER_RE.match(line)
                or LAYER_MARKER_RE.match(line)):
            model_started = True
            continue
        if not model_started:
            continue
        match = M204_RE.match(line)
        if not match:
            continue
        values = {key.upper(): float(value) for key, value in TOKEN_RE.findall(match.group(1) or "")}
        for key, value in values.items():
            canonical = "P" if key in {"S", "P"} else key
            signature.append((canonical, value))
    return signature


def first_acceleration_mismatch(desktop: list[tuple[str, float]],
                                android: list[tuple[str, float]]) -> str:
    """Describe the first normalized acceleration command that diverges."""
    limit = min(len(desktop), len(android))
    for index in range(limit):
        if desktop[index] != android[index]:
            return f"index={index}, desktop={desktop[index][0]}{desktop[index][1]:g}, Android={android[index][0]}{android[index][1]:g}"
    if len(desktop) != len(android):
        return f"sequence length desktop={len(desktop)}, Android={len(android)}"
    return "none"


def first_feature_mismatch(desktop: list[str], android: list[str]) -> str:
    """Locate the first canonical toolpath-feature transition divergence."""
    limit = min(len(desktop), len(android))
    for index in range(limit):
        if desktop[index] != android[index]:
            return (
                f"index={index}, desktop={desktop[index]}, Android={android[index]}"
            )
    if len(desktop) != len(android):
        return f"sequence length desktop={len(desktop)}, Android={len(android)}"
    return "none"


def relative_diff(reference: float, candidate: float) -> float:
    """Return candidate error relative to the desktop reference baseline.

    G3's estimate tolerance is defined against the desktop slice. Using the
    larger value as the denominator made positive Android drift look smaller
    than the same-sized negative drift and could accept a value above the
    stated tolerance.
    """
    denominator = abs(reference)
    if denominator == 0:
        return 0.0 if candidate == 0 else float("inf")
    return abs(candidate - reference) / denominator


def travel_diagnostic(desktop: Metrics, android: Metrics) -> str:
    """Build a bounded program-level travel comparison, not a motion model."""
    groups = sorted(
        set(desktop.travel_by_layer_feedrate) | set(android.travel_by_layer_feedrate)
    )
    ranked = []
    for key in groups:
        left = desktop.travel_by_layer_feedrate.get(key, {})
        right = android.travel_by_layer_feedrate.get(key, {})
        left_distance = left.get("distance_mm", 0.0)
        right_distance = right.get("distance_mm", 0.0)
        ranked.append((abs(left_distance - right_distance), key, left, right))
    ranked.sort(key=lambda item: (-item[0], item[1]))
    group_text = "; ".join(
        f"{key}: distance_mm={left.get('distance_mm', 0.0):.3f}/"
        f"{right.get('distance_mm', 0.0):.3f}, "
        f"moves={int(left.get('moves', 0))}/{int(right.get('moves', 0))}, "
        f"nominal_seconds={left.get('nominal_seconds', 0.0):.3f}/"
        f"{right.get('nominal_seconds', 0.0):.3f}"
        for _, key, left, right in ranked[:8]
    ) or "no supported travel segments"

    left_segments = desktop.travel_segments
    right_segments = android.travel_segments
    mismatch = next(
        (index for index, pair in enumerate(zip(left_segments, right_segments))
         if pair[0] != pair[1]),
        min(len(left_segments), len(right_segments)),
    )
    if mismatch == len(left_segments) == len(right_segments):
        first_difference = "ordered travel segments match"
    else:
        def render(segments: list[tuple]) -> str:
            return "[" + ", ".join(
                f"layer={s[0]} {s[1]} F{s[2]:g} "
                f"({s[3]:g},{s[4]:g},{s[5]:g})->({s[6]:g},{s[7]:g},{s[8]:g}) "
                f"{s[9]:g}mm {s[10]}"
                for s in segments[mismatch:mismatch + 3]
            ) + "]"
        first_difference = (
            f"first ordered mismatch at travel index {mismatch}; "
            f"desktop={render(left_segments)}, Android={render(right_segments)}"
        )
    return (
        "diagnostic only; emitted travel moves grouped by model layer and feedrate; "
        "nominal time ignores acceleration, lookahead, firmware conditionals, and unsupported arcs; "
        f"top groups desktop/Android: {group_text}; {first_difference}"
    )


def metrics_report(metrics: Metrics) -> dict:
    """Serialize public metrics while keeping the full comparison stream private."""
    result = asdict(metrics)
    result.pop("travel_segments", None)
    return result


def compare(desktop: Metrics, android: Metrics, tolerance: float,
            profile_identity: dict | None = None) -> dict:
    checks: list[dict] = []

    def add(name: str, status: str, detail: str) -> None:
        checks.append({"name": name, "status": status, "detail": detail})

    # Major feature classes: Android must not omit anything desktop reports.
    # First account for explicitly documented cross-slicer role aliases, then
    # keep genuinely uncovered classes as a hard failure.
    desktop_features = set(desktop.feature_counts)
    android_features = set(android.feature_counts)
    direct_missing = desktop_features - android_features
    equivalent: dict[str, list[str]] = {}
    missing = []
    for feature in sorted(direct_missing):
        aliases = [alias for alias in FEATURE_ROLE_ALIASES.get(feature, ())
                   if alias in android_features]
        if aliases:
            equivalent[feature] = aliases
        else:
            missing.append(feature)
    add(
        "major_feature_classes",
        "pass" if not missing else "fail",
        "none missing" if not missing else "missing on Android: " + ", ".join(missing),
    )
    if profile_identity is not None:
        profile_result = profile_identity.get("result")
        failed_fields = profile_identity.get("failed_fields", [])
        add(
            "profile_identity",
            "pass" if profile_result == "pass" else "fail",
            f"{profile_identity.get('checked_fields', 0)} source-backed fields match" if profile_result == "pass" else
            "profile mismatch: " + ", ".join(str(field) for field in failed_fields),
        )
    add(
        "semantic_feature_aliases",
        "pass" if equivalent else "unavailable",
        "none" if not equivalent else "; ".join(
            f"{source} covered by {', '.join(targets)}"
            for source, targets in sorted(equivalent.items())
        ),
    )

    # Exact transition order is useful evidence but overly strict across harmless emitter changes.
    # Record it as pass/warn, while missing feature classes is the hard failure above.
    if desktop.feature_transitions == android.feature_transitions:
        add("feature_transition_sequence", "pass", "exact canonical transition sequence match")
    else:
        add(
            "feature_transition_sequence",
            "warn",
            f"desktop transitions={len(desktop.feature_transitions)}, Android={len(android.feature_transitions)}; "
            + first_feature_mismatch(desktop.feature_transitions, android.feature_transitions),
        )

    layer_diff = abs(desktop.layer_count - android.layer_count)
    add(
        "layer_count",
        "pass" if layer_diff == 0 else "fail",
        f"desktop={desktop.layer_count}, Android={android.layer_count}",
    )

    for name in ("print_time_seconds", "filament_mm", "filament_g"):
        a = getattr(desktop, name)
        b = getattr(android, name)
        if a is None or b is None:
            add(name, "unavailable", f"desktop={a}, Android={b}")
            continue
        diff = relative_diff(a, b)
        add(
            name,
            "pass" if diff <= tolerance else "fail",
            f"desktop={a:.6g}, Android={b:.6g}, delta={diff:.2%}, tolerance={tolerance:.2%}",
        )

    # Move counts are diagnostics because slicers can segment identical paths
    # differently. Total positive extrusion distance is not: a large mismatch
    # can reveal missing or extra deposited material even when exported header
    # estimates happen to match, so keep it fail-closed at the 5% geometry
    # tolerance.
    for name in ("extrusion_moves", "travel_moves"):
        a = float(getattr(desktop, name))
        b = float(getattr(android, name))
        diff = relative_diff(a, b)
        add(
            name,
            "pass" if diff <= 0.05 else "warn",
            f"desktop={a:.6g}, Android={b:.6g}, delta={diff:.2%}",
        )

    desktop_linear_time = (
        desktop.nominal_linear_extrusion_seconds
        + desktop.nominal_linear_travel_seconds
        + desktop.nominal_arc_extrusion_seconds
        + desktop.nominal_arc_travel_seconds
    )
    android_linear_time = (
        android.nominal_linear_extrusion_seconds
        + android.nominal_linear_travel_seconds
        + android.nominal_arc_extrusion_seconds
        + android.nominal_arc_travel_seconds
    )
    desktop_path = desktop.linear_xyz_path_mm + desktop.arc_path_mm
    android_path = android.linear_xyz_path_mm + android.arc_path_mm
    path_diff = relative_diff(desktop_path, android_path)
    nominal_time_diff = relative_diff(desktop_linear_time, android_linear_time)
    add(
        "nominal_linear_motion_diagnostic",
        "pass" if max(path_diff, nominal_time_diff) <= tolerance else "warn",
        "linear XYZ plus XY I/J arcs; ignores acceleration, firmware planning, "
        "E-only moves, and unsupported arc forms. "
        f"unsupported_arcs desktop={desktop.unsupported_arc_moves}, "
        f"Android={android.unsupported_arc_moves}; "
        f"path_mm desktop={desktop_path:.6g} (linear={desktop.linear_xyz_path_mm:.6g}, "
        f"arc={desktop.arc_path_mm:.6g}), Android={android_path:.6g} "
        f"(linear={android.linear_xyz_path_mm:.6g}, arc={android.arc_path_mm:.6g}), "
        f"delta={path_diff:.2%}; "
        f"nominal_seconds desktop={desktop_linear_time:.6g}, "
        f"Android={android_linear_time:.6g}, delta={nominal_time_diff:.2%}; "
        f"extrusion_seconds desktop={desktop.nominal_linear_extrusion_seconds + desktop.nominal_arc_extrusion_seconds:.6g}/"
        f"Android={android.nominal_linear_extrusion_seconds + android.nominal_arc_extrusion_seconds:.6g}; "
        f"travel_seconds desktop={desktop.nominal_linear_travel_seconds + desktop.nominal_arc_travel_seconds:.6g}/"
        f"Android={android.nominal_linear_travel_seconds + android.nominal_arc_travel_seconds:.6g}",
    )

    # Move totals alone can obscure a support regression when an engine emits
    # the same feature classes but deposits substantially different geometry.
    # Count deposited XYZ distance only, excluding travel because feature
    # comments are not consistently reset before non-extruding motion.
    role_names = (set(desktop.feature_extrusion_path_mm)
                  | set(android.feature_extrusion_path_mm)
                  | set(desktop.feature_positive_e_mm)
                  | set(android.feature_positive_e_mm))
    role_diagnostics = []
    role_has_large_delta = False
    for role in sorted(role_names):
        desktop_path = desktop.feature_extrusion_path_mm.get(role, 0.0)
        android_path = android.feature_extrusion_path_mm.get(role, 0.0)
        desktop_e = desktop.feature_positive_e_mm.get(role, 0.0)
        android_e = android.feature_positive_e_mm.get(role, 0.0)
        path_delta = relative_diff(desktop_path, android_path)
        e_delta = relative_diff(desktop_e, android_e)
        role_has_large_delta |= max(path_delta, e_delta) > 0.05
        role_diagnostics.append((max(abs(desktop_path - android_path),
                                     abs(desktop_e - android_e)), role,
                                 desktop_path, android_path, path_delta,
                                 desktop_e, android_e, e_delta))
    role_diagnostics.sort(reverse=True)
    shown_roles = role_diagnostics[:8]
    role_detail = "; ".join(
        f"{role}: path {a_path:.6g}/{b_path:.6g} mm ({path_delta:.2%}), "
        f"E {a_e:.6g}/{b_e:.6g} mm ({e_delta:.2%})"
        for _, role, a_path, b_path, path_delta, a_e, b_e, e_delta in shown_roles
    ) or "no feature-labelled motion"
    add(
        "per_feature_toolpath_diagnostic",
        "warn" if role_has_large_delta else "pass",
        "diagnostic only; deposited XYZ path excludes travel; "
        "desktop/Android values are deposited path mm then positive E mm: " + role_detail,
    )

    accounting_details = []
    for label, metrics in (("desktop", desktop), ("Android", android)):
        positive_xyz = sum(values.get("positive_xyz_e_mm", 0.0)
                           for values in metrics.extrusion_accounting.values())
        scopes = "; ".join(
            f"{scope}: XYZ-positive E={values.get('positive_xyz_e_mm', 0.0):.6g}, "
            f"E-only positive={values.get('positive_e_only_mm', 0.0):.6g}, "
            f"retracted={values.get('retracted_e_mm', 0.0):.6g}, "
            f"net={values.get('net_e_mm', 0.0):.6g} mm"
            for scope, values in metrics.extrusion_accounting.items()
        )
        residual = ("unavailable" if metrics.filament_mm is None else
                    f"{metrics.filament_mm - positive_xyz:.6g} mm")
        accounting_details.append(f"{label} [{scopes}]; header minus all XYZ-positive E={residual}")
    add(
        "filament_accounting_diagnostic",
        "warn",
        "emitted commands only, not measured usage; firmware conditionals are not evaluated; "
        "XYZ-positive E can include retraction recovery and zero-distance XYZ commands. "
        "after_first_layer includes later templates/shutdown, not just the object. "
        "No adjustment to hard checks: " + " | ".join(accounting_details),
    )

    # Emit more detailed travel evidence only for a failed comparison. This
    # warning is diagnostic-only and is never part of hard_fail/evidence gates.
    if any(check["status"] == "fail" for check in checks):
        add("travel_path_diagnostic", "warn", travel_diagnostic(desktop, android))

    desktop_e = desktop.positive_e_mm
    android_e = android.positive_e_mm
    extrusion_diff = relative_diff(desktop_e, android_e)
    add(
        "positive_e_mm",
        "pass" if extrusion_diff <= 0.05 else "fail",
        f"desktop={desktop_e:.6g}, Android={android_e:.6g}, "
        f"delta={extrusion_diff:.2%}, tolerance=5.00%",
    )

    desktop_acceleration = acceleration_signature(Path(desktop.source), desktop.archive_member)
    android_acceleration = acceleration_signature(Path(android.source), android.archive_member)
    if not desktop_acceleration or not android_acceleration:
        add(
            "acceleration_command_profile",
            "unavailable",
            f"desktop commands={len(desktop_acceleration)}, Android={len(android_acceleration)}",
        )
    elif desktop_acceleration == android_acceleration:
        add(
            "acceleration_command_profile",
            "pass",
            "ordered normalized M204 command sequence matches",
        )
    else:
        add(
            "acceleration_command_profile",
            "warn",
            "normalized M204 sequence differs: "
            + first_acceleration_mismatch(desktop_acceleration, android_acceleration),
        )

    hard_fail = any(c["status"] == "fail" for c in checks)
    # G3 cannot pass if neither filament representation nor print time is available from both.
    time_check = next(c for c in checks if c["name"] == "print_time_seconds")
    filament_checks = [c for c in checks if c["name"] in {"filament_mm", "filament_g"}]
    evidence_complete = (
        time_check["status"] != "unavailable"
        and any(c["status"] != "unavailable" for c in filament_checks)
    )
    return {
        "tolerance": tolerance,
        "profile_identity": profile_identity,
        "checks": checks,
        "evidence_complete": evidence_complete,
        "result": "pass" if not hard_fail and evidence_complete else "fail",
    }


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("desktop", type=Path)
    p.add_argument("android", type=Path)
    p.add_argument("--plate-member")
    p.add_argument("--tolerance", type=float, default=0.02)
    p.add_argument("--desktop-profile", type=Path,
                   help="Bambu .gcode.3mf, resolved G-code, or project settings JSON used for the slice")
    p.add_argument("--desktop-profile-overlay", type=Path, action="append", default=[],
                   help="explicit Bambu project/object override JSON/3MF; repeatable")
    p.add_argument("--native-config", type=Path,
                   help="native config.ini used for the Android slice")
    p.add_argument("--json-out", type=Path)
    args = p.parse_args()

    if (args.desktop_profile is None) != (args.native_config is None):
        p.error("--desktop-profile and --native-config must be supplied together")

    desktop = parse_metrics(args.desktop, args.plate_member)
    android = parse_metrics(args.android, args.plate_member)
    profile_identity = None
    if args.desktop_profile is not None:
        # Keep the import local so the comparator remains usable as a small
        # standalone metrics library in environments that only need G-code.
        from verify_g3_profile import merged_desktop_settings, read_native_settings, verify
        profile_identity = verify(
            merged_desktop_settings(args.desktop_profile, args.desktop_profile_overlay),
            read_native_settings(args.native_config),
        )
    comparison = compare(desktop, android, args.tolerance, profile_identity)
    report = {
        "desktop": metrics_report(desktop),
        "android": metrics_report(android),
        "comparison": comparison,
    }

    rendered = json.dumps(report, indent=2)
    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(rendered + "\n")
    print(rendered)
    raise SystemExit(0 if comparison["result"] == "pass" else 2)


if __name__ == "__main__":
    main()
