#!/usr/bin/env python3

from pathlib import Path
import tempfile
import unittest
from zipfile import ZipFile

from compare_gcode import acceleration_signature, compare, parse_metrics


GCODE_A = """; generated by OrcaSlicer
; estimated printing time (normal mode) = 1m 40s
; filament used [mm] = 1000.0
; filament used [g] = 3.00
G90
M82
G92 E0
G1 Z0.20 F600
;TYPE:Outer wall
G1 X10 Y0 E1.0
G1 X10 Y10 E2.0
;TYPE:Sparse infill
G1 X0 Y0 E3.0
G1 Z0.40
;TYPE:Outer wall
G1 X20 Y0 E4.0
"""

GCODE_B = """; generated by Android port
; estimated printing time (normal mode) = 1m 41s
; filament used [mm] = 1008.0
; filament used [g] = 3.02
G90
M82
G92 E0
G1 Z0.20 F600
; FEATURE: External perimeter
G1 X10 Y0 E1.0
G1 X10 Y10 E2.0
; FEATURE: Internal infill
G1 X0 Y0 E3.0
G1 Z0.40
; FEATURE: External perimeter
G1 X20 Y0 E4.0
"""

GCODE_MISSING_FEATURE = GCODE_B.replace("; FEATURE: Internal infill\n", "")

GCODE_ACCELERATION_EQUIVALENT = GCODE_A.replace("G90\n", "G90\nM204 S1500\nM204 S500\n")
GCODE_ACCELERATION_NATIVE = GCODE_B.replace("G90\n", "G90\nM204 P1500\nM204 P500\n")


class CompareGcodeTests(unittest.TestCase):
    def test_profile_identity_is_a_hard_check_when_attached(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            desktop = parse_metrics(self.write(root, "a.gcode", GCODE_A), None)
            android = parse_metrics(self.write(root, "b.gcode", GCODE_B), None)
            report = compare(
                desktop,
                android,
                0.02,
                {"result": "fail", "failed_fields": ["fill_density"]},
            )
            self.assertEqual("fail", report["result"])
            self.assertEqual("fail", next(
                check for check in report["checks"] if check["name"] == "profile_identity"
            )["status"])

    def write(self, root: Path, name: str, content: str) -> Path:
        path = root / name
        path.write_text(content)
        return path

    def test_plain_gcode_semantic_match_within_two_percent(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            a = parse_metrics(self.write(root, "a.gcode", GCODE_A), None)
            b = parse_metrics(self.write(root, "b.gcode", GCODE_B), None)
            result = compare(a, b, 0.02)
            self.assertEqual(result["result"], "pass")
            self.assertTrue(result["evidence_complete"])
            self.assertEqual(a.layer_count, 2)
            self.assertEqual(b.layer_count, 2)
            self.assertAlmostEqual(a.positive_e_mm, 4.0)
            self.assertAlmostEqual(b.positive_e_mm, 4.0)

    def test_feature_toolpath_diagnostic_reports_deposited_path_and_extrusion(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            desktop = parse_metrics(self.write(root, "desktop.gcode", GCODE_A), None)
            android = parse_metrics(self.write(root, "android.gcode", GCODE_B), None)

            self.assertAlmostEqual(40.0, desktop.feature_extrusion_path_mm["outer_wall"])
            self.assertAlmostEqual(3.0, desktop.feature_positive_e_mm["outer_wall"])
            self.assertAlmostEqual(14.1421356, desktop.feature_extrusion_path_mm["sparse_infill"], places=5)
            diagnostic = next(
                check for check in compare(desktop, android, 0.02)["checks"]
                if check["name"] == "per_feature_toolpath_diagnostic"
            )
            self.assertIn("outer_wall", diagnostic["detail"])
            self.assertIn("path", diagnostic["detail"])
            self.assertIn("E", diagnostic["detail"])

    def test_filament_ledger_separates_priming_and_recovery_without_changing_gates(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            model = GCODE_A.replace("G90\n", ";LAYER_CHANGE\nG90\n")
            priming = "M83\nG1 X5 E10\nG1 E-0.8\nG92 E0\nG1 E0.8\n"
            desktop = parse_metrics(self.write(root, "desktop.gcode", priming + model), None)
            android = parse_metrics(self.write(root, "android.gcode", model), None)
            before = desktop.extrusion_accounting["before_first_layer"]
            self.assertAlmostEqual(10, before["positive_xyz_e_mm"])
            self.assertAlmostEqual(0.8, before["positive_e_only_mm"])
            self.assertAlmostEqual(0.8, before["retracted_e_mm"])
            self.assertAlmostEqual(10, before["net_e_mm"])
            self.assertAlmostEqual(4, desktop.extrusion_accounting["after_first_layer"]["positive_xyz_e_mm"])
            # The established model-positive-E check retains its original scope.
            self.assertAlmostEqual(4, desktop.positive_e_mm)
            result = compare(desktop, android, 0.02)
            self.assertEqual("pass", result["result"])
            diagnostic = next(c for c in result["checks"] if c["name"] == "filament_accounting_diagnostic")
            self.assertIn("before_first_layer: XYZ-positive E=10", diagnostic["detail"])
            self.assertIn("header minus all XYZ-positive E=986 mm", diagnostic["detail"])
            self.assertIn("not measured usage", diagnostic["detail"])

    def test_filament_ledger_absolute_resets_are_not_extrusion(self):
        with tempfile.TemporaryDirectory() as td:
            text = "M82\nG92 E100\nG1 X1 E101\nG1 E100.2\nG92 E0\nG1 E0.8\n;LAYER_CHANGE\nG1 X2 E2.8\n"
            metrics = parse_metrics(self.write(Path(td), "absolute.gcode", text), None)
            before = metrics.extrusion_accounting["before_first_layer"]
            self.assertAlmostEqual(1, before["positive_xyz_e_mm"])
            self.assertAlmostEqual(0.8, before["positive_e_only_mm"])
            self.assertAlmostEqual(0.8, before["retracted_e_mm"])
            self.assertAlmostEqual(1, before["net_e_mm"])
            self.assertAlmostEqual(2, metrics.extrusion_accounting["after_first_layer"]["positive_xyz_e_mm"])

    def test_filament_ledger_does_not_invent_startup_boundary(self):
        with tempfile.TemporaryDirectory() as td:
            metrics = parse_metrics(self.write(Path(td), "unscoped.gcode", GCODE_A), None)
            self.assertEqual({"unscoped"}, set(metrics.extrusion_accounting))
            self.assertAlmostEqual(4, metrics.extrusion_accounting["unscoped"]["positive_xyz_e_mm"])

    def test_filament_ledger_records_conditional_emission_without_predicting_firmware(self):
        with tempfile.TemporaryDirectory() as td:
            text = "M83\nM622 J1\nG1 X5 E10\nM623\n;LAYER_CHANGE\nG2 I5 J0 E2\nG1 E0.8\n"
            metrics = parse_metrics(self.write(Path(td), "conditional.gcode", text), None)
            self.assertAlmostEqual(10, metrics.extrusion_accounting["before_first_layer"]["positive_xyz_e_mm"])
            self.assertAlmostEqual(2, metrics.extrusion_accounting["after_first_layer"]["positive_xyz_e_mm"])
            self.assertAlmostEqual(0.8, metrics.extrusion_accounting["after_first_layer"]["positive_e_only_mm"])

    def test_filament_header_failure_is_not_erased_by_matching_ledger(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            desktop = parse_metrics(self.write(root, "desktop.gcode", GCODE_A), None)
            android = parse_metrics(self.write(root, "android.gcode", GCODE_A.replace("1000.0", "900.0")), None)
            self.assertEqual(desktop.extrusion_accounting, android.extrusion_accounting)
            report = compare(desktop, android, 0.02)
            self.assertEqual("fail", report["result"])
            self.assertEqual("fail", next(c for c in report["checks"] if c["name"] == "filament_mm")["status"])

    def test_estimate_tolerance_is_measured_from_desktop_reference(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            desktop = parse_metrics(self.write(root, "desktop.gcode", GCODE_A), None)
            android_text = GCODE_B.replace("1m 41s", "1m 42.04s")
            android_text = android_text.replace("1008.0", "1020.4").replace("3.02", "3.0612")
            android = parse_metrics(self.write(root, "android.gcode", android_text), None)

            result = compare(desktop, android, tolerance=0.02)

            self.assertEqual("fail", result["result"])
            time_check = next(c for c in result["checks"] if c["name"] == "print_time_seconds")
            self.assertEqual("fail", time_check["status"])
            self.assertIn("delta=2.04%", time_check["detail"])

    def test_zero_desktop_estimate_cannot_hide_nonzero_android_estimate(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            desktop_text = GCODE_A.replace("filament used [mm] = 1000.0", "filament used [mm] = 0")
            android_text = GCODE_B.replace("filament used [mm] = 1008.0", "filament used [mm] = 1")
            desktop = parse_metrics(self.write(root, "desktop.gcode", desktop_text), None)
            android = parse_metrics(self.write(root, "android.gcode", android_text), None)

            result = compare(desktop, android, tolerance=0.02)

            filament_check = next(c for c in result["checks"] if c["name"] == "filament_mm")
